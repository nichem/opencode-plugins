import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { transformAsync } from "@babel/core"
import solid from "babel-preset-solid"
import typescript from "@babel/preset-typescript"

const source = new URL("../tui.tsx", import.meta.url)
const output = new URL("../tui.js", import.meta.url)
const compiled = await transformAsync(await readFile(source, "utf8"), {
  filename: fileURLToPath(source), configFile: false, babelrc: false,
  presets: [[solid, { moduleName: "@opentui/solid", generate: "universal" }], typescript],
})
if (!compiled?.code) throw new Error("opencode-deepseek-behavior: TUI compilation produced no output")
const contents = `// Generated by npm run build:tui; edit tui.tsx instead.\n${compiled.code}\n`
if (process.argv.includes("--check")) {
  const existing = await readFile(output, "utf8").catch(() => "")
  if (existing.replace(/\r\n/g, "\n") !== contents)
    throw new Error("opencode-deepseek-behavior: tui.js is out of date; run npm run build:tui")
} else {
  await writeFile(output, contents)
}
